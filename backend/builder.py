"""Role 2: turn a confirmed spec into real, on-disk Hermes agents.

Hermes auto-injects AGENTS.md from the working directory in one-shot mode, and
`--in DIR` sets that directory. So each agent becomes a folder carrying its own
identity, and is invoked with:

    hermes -z "<task>" --in <agent folder> -t <toolsets> -s <skills> --reasoning <level>

That makes a created team persistent and inspectable: the user can open any
agent's AGENTS.md and edit it without going through this app, and Hermes loads
the edit on the next run.

Layout under AGENTFORGE_TEAMS_DIR (default ./teams):

    teams/<owner>/<team_name>/
      team.json             the spec, as confirmed
      AGENTS.md             supervisor identity + roster
      agents/<name>/AGENTS.md

Each user's agents live under their own folder, so one account's teams are never
reachable from another's.
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Dict, List

from .schema import SubAgent, TeamSpec

TEAMS_DIR = Path(os.getenv(
    "AGENTFORGE_TEAMS_DIR",
    Path(__file__).resolve().parent.parent / "teams",
))


MEMORY_FILE = "memory.md"


def _memory_seed(a: SubAgent) -> str:
    return f"""# {a.nickname or a.name} — memory

Written by this agent, read by it at the start of every run. Anything here is
carried between runs; everything else is forgotten when a run ends.

Keep it short and specific: things learned about how this job actually works,
corrections the user has made, paths and names worth remembering. Not a log of
what happened.

<!-- The agent appends below. Edit or prune this file freely. -->
"""


def _memory_clause(a: SubAgent) -> str:
    if not a.memory_enabled:
        return ""
    return f"""
## Your memory

`{MEMORY_FILE}` sits beside this file in your working directory and is yours
alone. Read it before you start. When a run teaches you something that would
make you better next time — a correction, a preference, a path, a quirk of the
data — append a short line to it. Never store secrets there, never let it grow
past a page, and never treat it as a log of events.
"""


def _personality_clause(a: SubAgent) -> str:
    if not a.personality:
        return ""
    return f"""
## Your manner

{a.personality}

This shapes how you say things, never what you do. Accuracy, your instructions
and your tool limits always come first; if being in character would mean
glossing over a problem, drop the character and say the plain thing.
"""


def _workspace_rule() -> str:
    from .workspace import rule_text          # local: avoids an import cycle
    from .trust import data_rule
    return rule_text() + "\n" + data_rule()


def _agents_md_for_sub(spec: TeamSpec, a: SubAgent) -> str:
    grants = []
    if a.toolsets:
        grants.append(f"- Toolsets granted: {', '.join(a.toolsets)}")
    if a.skills:
        grants.append(f"- Skills preloaded: {', '.join(a.skills)}")
    grants.append(f"- Reasoning effort: {a.reasoning}")
    io = []
    if a.inputs:
        io.append(f"- Expects: {', '.join(a.inputs)}")
    if a.outputs:
        io.append(f"- Produces: {', '.join(a.outputs)}")

    called = f" (called **{a.nickname}**)" if a.nickname else ""
    return f"""# {a.name}{called}

Sub-agent of the **{spec.team_name}** team. Role: {a.role}

## Instructions

{a.system_prompt}
{_personality_clause(a)}{_memory_clause(a)}
## Operating rules

{chr(10).join(grants)}
{chr(10).join(io)}
- You are one step in a team. Do the job named above and nothing beyond it.
- Return your finished result as plain text. Do not ask clarifying questions:
  if something is missing, state the assumption you made and continue.
- Your tool grant is enforced by the runtime. If a task needs something outside
  it, say so in your result rather than attempting a workaround.

{_workspace_rule()}
<!-- Generated by AgentForge from team.json. Edit freely: Hermes loads this file
     on each run. Rebuilding the team from the app will overwrite it. -->
"""


def _agents_md_for_team(spec: TeamSpec) -> str:
    roster = "\n".join(
        f"- **{a.nickname or a.name}**"
        + (f" (`{a.name}`)" if a.nickname else "")
        + f" — {a.role}"
        f" (toolsets: {', '.join(a.toolsets) or 'none'}"
        f"{'; skills: ' + ', '.join(a.skills) if a.skills else ''})"
        for a in spec.sub_agents
    )
    rules = "\n".join(f"- {r.from_agent} → {r.to_agent} when {r.when}"
                      for r in spec.handoff_rules) or "- use your judgement"
    gaps = ""
    if spec.unsupported_requests:
        gaps = ("\n## Known gaps\n\n"
                + "\n".join(f"- {g}" for g in spec.unsupported_requests) + "\n")

    return f"""# {spec.team_name}

{spec.summary}

## Goal

{spec.main_agent.goal}

## Supervisor instructions

{spec.main_agent.system_prompt}

## Team

{roster}

## Handoffs

{rules}
{gaps}
{_workspace_rule()}
<!-- Generated by AgentForge. The agents live in ./agents/<name>/AGENTS.md -->
"""


def _safe(name: str) -> str:
    """Keep a user-supplied name from escaping the teams directory."""
    cleaned = re.sub(r"[^A-Za-z0-9._-]", "_", (name or "shared").strip())
    cleaned = cleaned.lstrip(".") or "shared"
    return cleaned[:64]


def remove_agent_dir(team_name: str, agent_name: str,
                     owner: str = "shared") -> bool:
    """Delete one agent's folder, including its memory. Irreversible.

    The path is rebuilt from sanitised parts and then checked to be inside
    this team's agents directory before anything is removed, so a crafted
    name cannot reach another team, another user, or the source tree.
    """
    import shutil

    agents_root = (TEAMS_DIR / _safe(owner) / _safe(team_name) / "agents")
    target = agents_root / _safe(agent_name)
    try:
        inside = target.resolve().is_relative_to(agents_root.resolve())
    except (OSError, ValueError):
        return False
    if not inside or target == agents_root or not target.is_dir():
        return False
    shutil.rmtree(target, ignore_errors=True)
    return not target.exists()


def remove_team_dir(team_name: str, owner: str = "shared") -> bool:
    """Delete a team's whole folder: agents, memories and workspace files.

    Bounded the same way as a single agent: the path is rebuilt from
    sanitised parts and checked to sit inside this owner's directory, which
    is itself inside TEAMS_DIR. A name that resolves anywhere else removes
    nothing.
    """
    import shutil

    owner_root = TEAMS_DIR / _safe(owner)
    target = owner_root / _safe(team_name)
    try:
        inside = (target.resolve().is_relative_to(owner_root.resolve())
                  and target.resolve() != owner_root.resolve())
    except (OSError, ValueError):
        return False
    if not inside or not target.is_dir():
        return False
    shutil.rmtree(target, ignore_errors=True)
    return not target.exists()


def build(spec: TeamSpec, owner: str = "shared") -> Dict[str, object]:
    """Write the team to disk under its owner. Returns the paths created."""
    root = TEAMS_DIR / _safe(owner) / _safe(spec.team_name)
    (root / "agents").mkdir(parents=True, exist_ok=True)
    # The team's only reachable folder. Created even when empty, so an agent
    # always has somewhere legitimate to write and never improvises a path.
    (root / "workspace").mkdir(parents=True, exist_ok=True)

    (root / "team.json").write_text(
        json.dumps(spec.model_dump(by_alias=True), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    (root / "AGENTS.md").write_text(_agents_md_for_team(spec), encoding="utf-8")

    agent_dirs: Dict[str, str] = {}
    for a in spec.sub_agents:
        d = root / "agents" / a.name
        d.mkdir(parents=True, exist_ok=True)
        (d / "AGENTS.md").write_text(_agents_md_for_sub(spec, a), encoding="utf-8")
        # Memory belongs to the agent: seed it once, then never overwrite it.
        # Rebuilding a team must not wipe what its agents have learned.
        mem = d / MEMORY_FILE
        if a.memory_enabled and not mem.exists():
            mem.write_text(_memory_seed(a), encoding="utf-8")
        agent_dirs[a.name] = str(d)

    return {
        "team_dir": str(root),
        "supervisor_dir": str(root),
        "agent_dirs": agent_dirs,
        "files": [str(p.relative_to(root)) for p in sorted(root.rglob("*")) if p.is_file()],
    }


def agent_dir(team_name: str, agent_name: str, owner: str = "shared") -> str:
    return str(TEAMS_DIR / _safe(owner) / _safe(team_name) / "agents"
               / _safe(agent_name))


def team_dir(team_name: str, owner: str = "shared") -> str:
    return str(TEAMS_DIR / _safe(owner) / _safe(team_name))
